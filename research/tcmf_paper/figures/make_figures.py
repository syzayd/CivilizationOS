def _cosine(a: list[float], b: list[float]) -> float:
    va, vb = np.asarray(a, dtype=np.float64), np.asarray(b, dtype=np.float64)
    denom = float(np.linalg.norm(va) * np.linalg.norm(vb))
    return float(np.dot(va, vb) / denom) if denom > 0 else 0.0


def build_fig1_scenario_json() -> dict:
    """Generate the illustrative scenario and shape it into the committed JSON schema."""
    sc = generate(FIG1_SCENARIO_ID, FIG1_CONFIG, seed=FIG1_SEED)

    events = [
        {
            "id": ev.id, "text": ev.text, "tick": ev.tick, "topic": ev.topic,
            "kind": ev.kind, "embedding": [round(x, 6) for x in ev.embedding],
        }
        for ev in sc.events
    ]
    # Assign display ids in generation order (post-shuffle, deterministic given FIG1_SEED) -
    # these memories are never inserted into a real MemoryStream for a figure-only scenario,
    # so MemorySpec.id is still "".
    memories = []
    for idx, m in enumerate(sc.memories):
        memories.append({
            "id": f"mem{idx}", "text": m.text, "tick": m.tick, "topic": m.topic,
            "label": m.label, "importance": m.importance,
            "embedding": [round(x, 6) for x in m.embedding],
        })

    return {
        "generator": "tcmfbench.generator.generate",
        "scenario_id": FIG1_SCENARIO_ID,
        "seed": FIG1_SEED,
        "config": {
            "dim": FIG1_CONFIG.dim, "n_topics": FIG1_CONFIG.n_topics,
            "chain_len": FIG1_CONFIG.chain_len, "n_distractors": FIG1_CONFIG.n_distractors,
            "n_noise": FIG1_CONFIG.n_noise,
            "witnesses_per_ancestor": FIG1_CONFIG.witnesses_per_ancestor,
        },
        "events": events,
        "edges": [list(e) for e in sc.edges],
        "crisis_event_id": sc.crisis_event_id,
        "memories": memories,
    }


def _kind_label(kind: str) -> str:
    return {"root_cause": "root cause", "decision": "decision", "crisis": "crisis"}.get(kind, kind)


def draw_fig1(data: dict, out_stub: Path) -> None:
    """Fig 1: the causal graph - ancestor chain + root cause vs. semantically-near
    distractors sitting off the causal path. Every position and cosine value below is
    derived from ``data``, i.e. the committed JSON, not typed in by hand."""
    events = {e["id"]: e for e in data["events"]}
    edges = [tuple(e) for e in data["edges"]]
    crisis_id = data["crisis_event_id"]
    memories = data["memories"]

    # order events root -> ... -> crisis by walking the edge chain
    incoming = {b for _, b in edges}
    order = [eid for eid in events if eid not in incoming]
    nxt = dict(edges)
    while order[-1] in nxt:
        order.append(nxt[order[-1]])

    # Data units are inches - figsize below must match the xlim/ylim spans used here, so
    # every text placement can be reasoned about directly in physical size.
    n_events = len(order)
    step = 1.0
    ex = {eid: 0.5 + i * step for i, eid in enumerate(order)}
    ey = {eid: 1.85 for eid in order}

    fig_w, fig_h = 3.3, 4.0
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    ax.set_xlim(0, fig_w)
    ax.set_ylim(0, fig_h)
    ax.axis("off")

    # causal-chain arrows
    for a, b in edges:
        ax.annotate(
            "", xy=(ex[b] - 0.20, ey[b]), xytext=(ex[a] + 0.20, ey[a]),
            arrowprops=dict(arrowstyle="-|>", color=COLOR_EDGE, lw=1.3, shrinkA=0, shrinkB=0),
        )

    # event nodes
    for eid in order:
        ev = events[eid]
        color = COLOR_CRISIS if eid == crisis_id else COLOR_CAUSAL
        ax.scatter([ex[eid]], [ey[eid]], s=170, color=color, zorder=3,
                   edgecolors="black", linewidths=0.6)
        ax.text(ex[eid], ey[eid] + 0.40, _kind_label(ev["kind"]),
                ha="center", va="bottom", fontsize=8.0, fontweight="bold")
        ax.text(ex[eid], ey[eid] - 0.40, f"topic {ev['topic']}",
                ha="center", va="top", fontsize=8.0, color="#444444")

    # witness memories under their causal-ancestor event, drawn from `memories`, not invented
    ancestor_ids = order[:-1]
    root_id = order[0]
    witness_by_event: dict[str, list[dict]] = {eid: [] for eid in ancestor_ids}
    distractors: list[dict] = []
    for m in memories:
        if m["label"] in ("gold_root", "gold_chain"):
            for eid in ancestor_ids:
                if events[eid]["topic"] == m["topic"]:
                    witness_by_event[eid].append(m)
        elif m["label"] == "distractor":
            distractors.append(m)

    for eid, ws in witness_by_event.items():
        for wi, m in enumerate(ws):
            wx, wy = ex[eid], ey[eid] - 0.95 - 0.62 * wi
            ax.scatter([wx], [wy], s=70, color=COLOR_CAUSAL, marker="s", zorder=3,
                       edgecolors="black", linewidths=0.4)
            ax.plot([ex[eid], wx], [ey[eid] - 0.40, wy + 0.12], "--", color=COLOR_CAUSAL,
                    lw=0.7, alpha=0.6, zorder=1)
            ax.text(wx + 0.16, wy, "witness", ha="left", va="center",
                    fontsize=8.0, color=COLOR_CAUSAL)

    # distractor cluster - semantically near the crisis, causally disconnected (no edge drawn),
    # stacked ABOVE the crisis's own kind label so it never competes for the same horizontal band
    crisis_x = ex[crisis_id]
    dist_y0 = ey[crisis_id] + 0.85
    for di, m in enumerate(distractors):
        dy = dist_y0 + 0.30 * di
        ax.scatter([crisis_x], [dy], s=70, color=COLOR_DISTRACTOR, marker="^", zorder=3,
                   edgecolors="black", linewidths=0.4)
    if distractors:
        ax.text(crisis_x, dist_y0 + 0.30 * (len(distractors) - 1) + 0.20,
                "distractors\n(off-path)", ha="center", va="bottom",
                fontsize=8.0, color=COLOR_DISTRACTOR)

    # ground the "semantically near / far" claim in real numbers, computed from data
    root_witnesses = witness_by_event.get(root_id, [])
    crisis_emb = events[crisis_id]["embedding"]
    if root_witnesses and distractors:
        cos_root = _cosine(root_witnesses[0]["embedding"], crisis_emb)
        cos_dist = _cosine(distractors[0]["embedding"], crisis_emb)
        mid_x = fig_w / 2
        ax.text(mid_x, 0.55, f"cos(root-cause witness, crisis) = {cos_root:.2f}",
                ha="center", va="bottom", fontsize=8.0, color=COLOR_SIM_ANNOT)
        ax.text(mid_x, 0.20, f"cos(distractor, crisis) = {cos_dist:.2f}",
                ha="center", va="bottom", fontsize=8.0, color=COLOR_SIM_ANNOT)

    fig.tight_layout(pad=0.25)
    fig.savefig(out_stub.with_suffix(".pdf"))
    fig.savefig(out_stub.with_suffix(".png"), dpi=220)
    plt.close(fig)


def _box(ax, xy, w, h, text, color, fontsize=8.0):
    x, y = xy
    box = FancyBboxPatch(
        (x - w / 2, y - h / 2), w, h, boxstyle="round,pad=0.02,rounding_size=0.06",
        linewidth=1.0, edgecolor="black", facecolor=color, alpha=0.9, zorder=2,
    )
    ax.add_patch(box)
    ax.text(x, y, text, ha="center", va="center", fontsize=fontsize, zorder=3)


def _arrow(ax, p0, p1):
    ax.add_patch(FancyArrowPatch(
        p0, p1, arrowstyle="-|>", mutation_scale=9, color=COLOR_EDGE, lw=1.1,
        shrinkA=2, shrinkB=2, zorder=1,
    ))


