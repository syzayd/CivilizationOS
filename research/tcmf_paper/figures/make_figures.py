def _box(ax, xy, w, h, text, color, fontsize=8.0):
    x, y = xy
    box = FancyBboxPatch(
        (x - w / 2, y - h / 2), w, h, boxstyle="round,pad=0.02,rounding_size=0.06",
        linewidth=1.0, edgecolor="black", facecolor=color, alpha=0.9, zorder=2,
    )
    ax.add_patch(box)
    ax.text(x, y, text, ha="center", va="center", fontsize=fontsize, zorder=3)


def _arrow(ax, p0, p1):
    ax.add_patch(FancyArrowPatch(
        p0, p1, arrowstyle="-|>", mutation_scale=9, color=COLOR_EDGE, lw=1.1,
        shrinkA=2, shrinkB=2, zorder=1,
    ))


# Stage text for Fig 2. Short for legibility at column width, but each phrase is a
