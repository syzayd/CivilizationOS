# One root-vs-hardest-distractor pair per seed, across the same 10 seeds ``run_theory.py``
# sweeps - so this figure's spread is the exact one already cited in main.tex (a 3.0x swing,
# 3.11-9.26), not one scenario's own distractors, which are too similar to each other to show
# cross-scenario spread on their own.

FIG3_SEEDS = tuple(range(1, 11))
FIG3_CONFIG = MixedConfig(n_distractors=20, n_noise=55)  # matches run_theory.py's defaults
FIG3_BOOST_KW = dict(threshold=0.45, clean=True, favor_root=False)  # matches run_theory.py
FIG3_LAM_MAX = 10.0


def build_fig3_pairs_json() -> dict:
    """One root-vs-worst-distractor pair per seed (the ``mult_required_lambda``-defining
    competitor), across the same 10 seeds ``run_theory.py`` sweeps - shaped into the committed
    JSON schema. Same generator, config and boost kwargs, so this figure's numbers are directly
    cross-checkable against ``results_theory.json``'s rows, not invented."""
    pairs = []
    for seed in FIG3_SEEDS:
        mat = M.materialize(generate_mixed(f"fig3_s{seed}", FIG3_CONFIG, seed=seed))
        e = M._episodic_scores(mat)
        ehat = M._minmax(e)
        b = M._causal_boosts(mat, **FIG3_BOOST_KW)
        root = mat.root_id
        distractors = sorted(M.distractor_ids(mat))

        # The competitor that drives mult_required_lambda for this seed: the one with the
        # largest (or unreachable) multiplicative crossover, i.e. the hardest to promote.
        def _mult_key(j: str) -> float:
            xc = T.mult_crossover_lambda(e[root], b[root], e[j], b[j])
            return math.inf if xc is None else xc
        worst_j = max(distractors, key=_mult_key)

        pairs.append({
            "seed": seed, "distractor_id": worst_j,
            "e_root": e[root], "e_j": e[worst_j],
            "ehat_root": ehat[root], "ehat_j": ehat[worst_j],
            "b_root": b[root], "b_j": b[worst_j],
            "mult_promotable": T.mult_promotable(e[root], b[root], e[worst_j], b[worst_j]),
            "mult_crossover_lambda": T.mult_crossover_lambda(
                e[root], b[root], e[worst_j], b[worst_j]),
            "additive_sufficient_lambda": T.additive_sufficient_lambda(
                ehat[root], b[root], ehat[worst_j], b[worst_j]),
            # the episodic-independent bound (Corollary 2.1) for this seed's full distractor set
            "additive_uniform_bound_lambda": T.additive_required_lambda(
                b, root, set(distractors)),
        })

    return {
        "generator": "tcmfbench.mixed.generate_mixed",
        "seeds": list(FIG3_SEEDS),
        "config": {"n_distractors": FIG3_CONFIG.n_distractors, "n_noise": FIG3_CONFIG.n_noise},
        "boost_kw": FIG3_BOOST_KW,
        "pairs": pairs,
    }


def draw_fig3(data: dict, out_stub: Path) -> None:
    """Fig 3: the fusion-operator theory as a picture (N10). Both operators' pairwise margins
    are affine in lambda (``theory.py``); this plots margin vs lambda for the root cause against
    its hardest-to-promote distractor, one pair per seed across the same 10 seeds
    ``run_theory.py`` sweeps. Multiplicative crossings scatter across lambda because each pair's
    crossing point depends on that scenario's own episodic scores (the exact 3.0x swing already
    reported in the text); additive crossings all sit left of that seed's lambda-independent
    bound. Every plotted value is read from ``data``, the committed JSON - not hand-drawn
    geometry."""
    pairs = data["pairs"]
    lam = np.linspace(0.0, FIG3_LAM_MAX, 400)
    n_unreachable = sum(1 for p in pairs if not p["mult_promotable"])

    # A fixed y-range sized to the PROMOTABLE pairs, so the rare (1/10 seeds here, ~1/200
    # pairs in the full sweep) unreachable case - whose margin diverges - clips off the top
    # instead of flattening every other line into an unreadable clump.
    MULT_YLIM = (-2.2, 3.0)
    ADD_YLIM = (-1.5, 3.0)

    fig, (ax_mult, ax_add) = plt.subplots(1, 2, figsize=(3.3, 2.2))

    for p in pairs:
        m_margin = ((p["e_root"] - p["e_j"])
                    + lam * (p["e_root"] * p["b_root"] - p["e_j"] * p["b_j"]))
        color = COLOR_CAUSAL if p["mult_promotable"] else COLOR_DISTRACTOR
        ax_mult.plot(lam, m_margin, color=color, lw=0.7, alpha=0.6)
        xc = p["mult_crossover_lambda"]
        if xc is not None and xc <= FIG3_LAM_MAX:
            ax_mult.scatter([xc], [0.0], s=8, color=color, zorder=3)
    ax_mult.axhline(0.0, color=COLOR_EDGE, lw=0.6)
    ax_mult.set_ylim(*MULT_YLIM)
    if n_unreachable:
        ax_mult.annotate(f"{n_unreachable}/{len(pairs)} seeds:\nno $\\lambda$ works",
                          xy=(FIG3_LAM_MAX * 0.55, MULT_YLIM[0] + 0.15),
                          fontsize=5.6, color=COLOR_DISTRACTOR)
    ax_mult.set_title("multiplicative", fontsize=7.5)
    ax_mult.set_xlabel(r"$\lambda$", fontsize=7.5)
    ax_mult.set_ylabel("margin (root - distractor)", fontsize=6.3)
    ax_mult.tick_params(labelsize=6)

    max_bound = 0.0
    for p in pairs:
        a_margin = (p["ehat_root"] - p["ehat_j"]) + lam * (p["b_root"] - p["b_j"])
        ax_add.plot(lam, a_margin, color=COLOR_CAUSAL, lw=0.7, alpha=0.6)
        xc = p["additive_sufficient_lambda"]
        if xc is not None and xc <= FIG3_LAM_MAX:
            ax_add.scatter([xc], [0.0], s=8, color=COLOR_CAUSAL, zorder=3)
        bound = p["additive_uniform_bound_lambda"]
        if math.isfinite(bound):
            max_bound = max(max_bound, bound)
    ax_add.set_ylim(*ADD_YLIM)
    if max_bound and max_bound <= FIG3_LAM_MAX:
        ax_add.axvline(max_bound, color=COLOR_CRISIS, lw=1.0, ls="--", zorder=2)
        ax_add.text(max_bound + 0.15, ADD_YLIM[1] * 0.85,
                     f"worst-seed\nbound={max_bound:.2f}", fontsize=5.6, color=COLOR_CRISIS)
    ax_add.axhline(0.0, color=COLOR_EDGE, lw=0.6)
    ax_add.set_title("additive", fontsize=7.5)
    ax_add.set_xlabel(r"$\lambda$", fontsize=7.5)
    ax_add.tick_params(labelsize=6)

    fig.tight_layout(pad=0.3, w_pad=1.1)
    fig.savefig(out_stub.with_suffix(".pdf"))
    fig.savefig(out_stub.with_suffix(".png"), dpi=220)
    plt.close(fig)


