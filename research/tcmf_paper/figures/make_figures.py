def _stack_down(top_y: float, heights: list[float], gap: float) -> list[float]:
    """Return center-y for each box, stacked top to bottom with a fixed edge-to-edge gap."""
    centers = []
    y = top_y
    for h in heights:
        y -= h / 2
        centers.append(y)
        y -= h / 2 + gap
    return centers


def draw_fig2(out_stub: Path) -> None:
    """Fig 2: TCMFRetriever.retrieve()'s pipeline, mirroring its real step order (steps 1-5
    in api/memory/tcmf.py). Two narrow columns (causal stream on the left, episodic stream on
    the right) stack vertically rather than spreading horizontally, so every box stays wide
    enough for an 8pt-legible label within the 3.3in single-column width. Both streams
    converge into one fusion box, then one ranked output.

    Data units are inches (figsize matches xlim/ylim exactly); box centers are computed by
    ``_stack_down`` from explicit heights and a fixed gap, so edges cannot silently overlap."""
    fig_w = 3.3
    x_causal, x_epi = 0.85, 2.45
    w_col = 1.5
    gap = 0.4
    top_y = 6.0

    causal_heights = [0.65, 0.8, 0.8, 1.15]  # crisis, bfs, ancestors, causal_boost
    causal_y = _stack_down(top_y, causal_heights, gap)
    crisis_xy, bfs_xy, anc_xy, boost_xy = ((x_causal, y) for y in causal_y)

    epi_heights = [0.65, 0.95]  # episodic memories, episodic score
    epi_y = _stack_down(top_y, epi_heights, gap)
    epi_in_xy, epi_score_xy = ((x_epi, y) for y in epi_y)

    stream_bottom = min(causal_y[-1] - causal_heights[-1] / 2, epi_y[-1] - epi_heights[-1] / 2)
    fusion_h, output_h = 1.35, 0.55
    fusion_y, output_y = _stack_down(stream_bottom - gap, [fusion_h, output_h], gap)
    fusion_xy = ((x_causal + x_epi) / 2, fusion_y)
    output_xy = ((x_causal + x_epi) / 2, output_y)

    fig_h = top_y + 0.6 - (output_y - output_h / 2)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    ax.set_xlim(0, fig_w)
    ax.set_ylim(output_y - output_h / 2 - 0.15, top_y + 0.55)
    ax.axis("off")

    _box(ax, crisis_xy, w_col, causal_heights[0], FIG2_STAGES["crisis_input"], "#F6D8C2")
    _box(ax, bfs_xy, w_col, causal_heights[1], FIG2_STAGES["bfs"], COLOR_DISTRACTOR)
    _box(ax, anc_xy, w_col, causal_heights[2], FIG2_STAGES["ancestors"], COLOR_DISTRACTOR)
    _box(ax, boost_xy, w_col, causal_heights[3], FIG2_STAGES["causal_boost"], COLOR_DISTRACTOR)

    _box(ax, epi_in_xy, w_col, epi_heights[0], FIG2_STAGES["episodic_input"], "#CCE5F5")
    _box(ax, epi_score_xy, w_col, epi_heights[1], FIG2_STAGES["episodic_score"], COLOR_CAUSAL)

    _box(ax, fusion_xy, 2.0, fusion_h, FIG2_STAGES["fusion"], "#777777")
    _box(ax, output_xy, 1.7, output_h, FIG2_STAGES["output"], "#999999")

    def _v_arrow(x, y_top_box, h_top, y_bot_box, h_bot):
        _arrow(ax, (x, y_top_box - h_top / 2), (x, y_bot_box + h_bot / 2))

    # causal stream, top to bottom
    for (y0, h0), (y1, h1) in zip(
        zip(causal_y, causal_heights), zip(causal_y[1:], causal_heights[1:])
    ):
        _v_arrow(x_causal, y0, h0, y1, h1)
    # episodic stream, top to bottom
    _v_arrow(x_epi, epi_y[0], epi_heights[0], epi_y[1], epi_heights[1])
    # both streams converge into fusion
    _arrow(ax, (x_causal + 0.35, boost_xy[1] - causal_heights[-1] / 2 + 0.1),
           (fusion_xy[0] - 0.5, fusion_xy[1] + fusion_h / 2 - 0.15))
    _arrow(ax, (x_epi - 0.35, epi_score_xy[1] - epi_heights[-1] / 2 + 0.1),
           (fusion_xy[0] + 0.5, fusion_xy[1] + fusion_h / 2 - 0.15))
    # fusion -> output
    _v_arrow(fusion_xy[0], fusion_xy[1], fusion_h, output_xy[1], output_h)

    fig.tight_layout(pad=0.25)
    fig.savefig(out_stub.with_suffix(".pdf"))
    fig.savefig(out_stub.with_suffix(".png"), dpi=220)
    plt.close(fig)


